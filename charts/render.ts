// Renders every chart in this folder to SVG, in English, Japanese and
// Indonesian and at two widths, into its project's content folder: <name>.svg
// for English and <name>.<lang>.svg for the others, and <name>-narrow.* for
// phones. Run with `npm run charts`; a test checks
// that the committed SVGs match what this produces.
import { writeFileSync } from 'node:fs'
import * as vega from 'vega'
import * as vl from 'vega-lite'
import * as attacks from './attacks-chart.ts'
import * as gate from './gate-chart.ts'
import * as screen from './screen-chart.ts'
import { textWidth } from './text-width.ts'
import { sizes } from './theme.ts'
import type { Chart, Lang, Size } from './theme.ts'

// Vega exports this hook at run time, but its type definitions leave it out.
;(vega as unknown as { textMetrics: { width: typeof textWidth } }).textMetrics.width = textWidth

export const charts: Chart[] = [gate, attacks, screen]
export const langs: Lang[] = ['en', 'ja', 'id']

/** chart.svg, chart.ja.svg, chart-narrow.svg, chart-narrow.ja.svg and so on. */
export function outPath(chart: Chart, lang: Lang, size: Size): URL {
  const base = size.name === 'narrow' ? `${chart.name}-narrow` : chart.name
  const file = lang === 'en' ? `${base}.svg` : `${base}.${lang}.svg`
  return new URL(`../src/content/projects/${chart.slug}/${file}`, import.meta.url)
}

export async function render(chart: Chart, lang: Lang, size: Size): Promise<string> {
  const view = new vega.View(vega.parse(vl.compile(chart.spec(lang, size)).spec), { renderer: 'none' })
  const svg = await view.toSVG()
  const note = `<!-- Generated by charts/${chart.name}.ts with Vega-Lite; edit that file, then run npm run charts. -->`
  return numberClipsFromOne(svg).replace(/^(<svg[^>]*>)/, `$1${note}`) + '\n'
}

// Vega numbers clip paths with a counter shared by every chart drawn in the
// same process, so a chart's file would depend on what was drawn before it.
// Numbering them afresh in each SVG keeps the output the same in any order.
function numberClipsFromOne(svg: string): string {
  const renumbered = new Map<string, string>()
  return svg.replace(/\bclip\d+\b/g, (id) => {
    if (!renumbered.has(id)) renumbered.set(id, `clip${renumbered.size + 1}`)
    return renumbered.get(id) ?? id
  })
}

/** Every chart, at every size, in every language. */
const allVersions = charts.flatMap((chart) => sizes.flatMap((size) => langs.map((lang) => ({ chart, size, lang }))))

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const { chart, size, lang } of allVersions) {
    writeFileSync(outPath(chart, lang, size), await render(chart, lang, size))
    console.log(`${chart.slug}/${chart.name} ${size.name} ${lang}`)
  }
}
